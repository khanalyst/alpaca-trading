"""Write the scan as a markdown report and freeze the strategy spec the trader reads.

Selection of what to trade is mechanical:

* ``confirmed``: the best discovery-ranked candidate that passes all five
  holdout confirmation tests.  Paper and live are both allowed.
* otherwise the paper-trial candidate is the ``weak`` candidate that passes
  the most tests, ties broken by discovery rank.  Paper only: the trader
  refuses live mode for it.  This tie-break rule was added after the first
  scan was seen, which the report states.
* no candidate: the spec carries ``candidate: null`` and the trader idles.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping

from edgefinder.catalogue import FAMILIES

STRATEGY_SCHEMA = "edgefinder.strategy.v1"


def _pct(x: Any, places: int = 1) -> str:
    return "n/a" if x is None else f"{100 * x:.{places}f}%"


def _num(x: Any, places: int = 2) -> str:
    return "n/a" if x is None else f"{x:.{places}f}"


def pick_strategy(scan: Mapping[str, Any]) -> tuple[dict[str, Any] | None, str | None]:
    confirmations = scan.get("confirmations", [])
    for c in confirmations:
        if c["verdict"] == "confirmed":
            return c, "confirmed"
    weak = [c for c in confirmations if c["verdict"] == "weak"]
    if weak:
        best = sorted(weak, key=lambda c: (-sum(c["tests"].values()), c["discovery_rank"]))[0]
        return best, "weak"
    return None, None


def strategy_spec(scan: Mapping[str, Any]) -> dict[str, Any]:
    pick, verdict = pick_strategy(scan)
    base = {"schema": STRATEGY_SCHEMA, "created_from_scan": scan.get("created_utc"),
            "code_commit": scan.get("code_commit"), "data_digest": scan.get("data_digest"),
            "data_last_date": scan.get("data_last_date")}
    if pick is None:
        return {**base, "candidate": None, "verdict": None, "live_allowed": False,
                "reason": "no candidate passed or nearly passed the holdout confirmation"}
    row = next(c for c in scan["candidates"] if c["id"] == pick["id"])
    family = FAMILIES[row["family"]]
    keep = ("years", "ann_excess", "ann_vol", "sharpe", "alpha", "alpha_t", "alpha_ir", "beta",
            "max_drawdown", "trades_per_year", "net_bps_per_trade", "breakeven_cost_multiple",
            "cagr_cash_earns_nothing", "exposure_overnight", "exposure_intraday")
    return {
        **base,
        "candidate": {"id": row["id"], "family": row["family"], "symbols": row["symbols"],
                      "params": row["params"]},
        "verdict": verdict, "live_allowed": verdict == "confirmed",
        "tests": pick["tests"], "holdout_alpha_p_holm": pick["holdout_alpha_p_holm"],
        "discovery_rank": pick["discovery_rank"],
        "mechanism": family.mechanism, "execution": family.execution,
        "evidence": {w: {k: row[w].get(k) for k in keep} for w in ("discovery", "holdout", "full")},
        "holdout_2x_cost": row.get("holdout_2x_cost"),
        "caveats": row.get("caveats", []),
        "selection_rule": ("first confirmed candidate by discovery rank" if verdict == "confirmed"
                           else "weak: most confirmation tests passed, then discovery rank "
                                "(rule chosen after the first scan was seen); paper only"),
    }


def render(scan: Mapping[str, Any]) -> str:
    rows = {c["id"]: c for c in scan["candidates"]}
    proto, mt, wf = scan["protocol"], scan["multiple_testing"], scan["walk_forward"]
    spec = strategy_spec(scan)
    lines: list[str] = []
    add = lines.append
    add(f"# Edge scan, data to {scan['data_last_date']}")
    add("")
    add(f"Generated by `python -m edgefinder.discover` at {scan['created_utc'][:19]} UTC from "
        f"commit `{(scan.get('code_commit') or 'unknown')[:10]}`. Data digest "
        f"`{scan['data_digest'][:16]}`. Every number below is in `scan.json` beside this file.")
    add("")
    add("## Verdict")
    add("")
    if spec["candidate"] is None:
        add("No candidate passed, or came close to passing, the holdout confirmation. "
            "The trader has nothing to trade.")
    else:
        ev = spec["evidence"]["holdout"]
        name = spec["candidate"]["id"]
        if spec["verdict"] == "confirmed":
            add(f"**Confirmed edge: `{name}`.** It passed all five holdout tests.")
        else:
            failed = [k for k, v in spec["tests"].items() if not v]
            add(f"**No candidate passed all five confirmation tests.** The best-supported "
                f"candidate is `{name}` (verdict *weak*: fails {', '.join(failed)}). "
                f"It is frozen as a **paper-only** trial; the trader refuses live mode for it.")
        add("")
        add(f"Holdout ({ev['years']} years): net excess return {_pct(ev['ann_excess'])} a year, "
            f"Sharpe {_num(ev['sharpe'])}, alpha {_pct(ev['alpha'])} a year "
            f"(t {_num(ev['alpha_t'])}, Holm-adjusted p {_num(spec['holdout_alpha_p_holm'], 3)}), "
            f"beta {_num(ev['beta'])}, maximum drawdown {_pct(ev['max_drawdown'])}, "
            f"{_num(ev['trades_per_year'], 0)} round trips a year, gross edge "
            f"{_num(ev['breakeven_cost_multiple'], 1)}x the modelled cost.")
    add("")
    add(f"The automatic selection itself, re-run every January on past data only "
        f"({wf.get('first_year')} to {wf.get('last_year')}): Sharpe {_num(wf.get('sharpe'))}, "
        f"alpha {_pct(wf.get('alpha'))} a year (t {_num(wf.get('alpha_t'))}), beta "
        f"{_num(wf.get('beta'))}, maximum drawdown {_pct(wf.get('max_drawdown'))}, "
        f"{wf.get('distinct_picks')} distinct picks. SPY over the same days: Sharpe "
        f"{_num(wf.get('spy_sharpe_same_days'))}, compound return "
        f"{_pct(wf.get('spy_cagr_same_days'))} a year against "
        f"{_pct(wf.get('cagr_with_bills'))} for the walk-forward (idle cash in bills).")
    add("")
    add("## Protocol")
    add("")
    add(f"- {scan['catalogue']['candidates']} candidates in {scan['catalogue']['families']} "
        f"families; {scan['catalogue']['eligible_for_selection']} have at least "
        f"{proto['min_discovery_years']:.0f} discovery years and can be selected.")
    add(f"- Statistics start {proto['stats_start']}. Discovery to {proto['discovery_end']}; "
        f"holdout from the next session to {scan['data_last_date']}.")
    add("- Edge measure: the information ratio of alpha against equal-weight buy and hold of "
        "the candidate's own funds, net of costs and bills, with Newey-West errors.")
    add(f"- Costs: `{proto['cost_model']}`, one full spread, 0.5 bps slippage a side and "
        f"sell-side fees per round trip (SPY {_num(proto['round_trip_bps'].get('SPY'))} bps, "
        f"VTI {_num(proto['round_trip_bps'].get('VTI'))} bps, VB "
        f"{_num(proto['round_trip_bps'].get('VB'))} bps).")
    add(f"- Confirmation of the top {proto['confirm_top']} by discovery rank, once, on the "
        f"holdout. Five tests: holdout alpha significant after Holm over the ten "
        f"(p < {proto['confirm_alpha']}); holdout Sharpe above zero; holdout gross edge at "
        f"least {proto['min_breakeven_multiple']:.0f}x cost; discovery deflated Sharpe at least "
        f"{proto['min_dsr']} for {mt['trials']} trials; holdout alpha still positive without "
        f"its best year.")
    add("")
    add("## Multiple testing over the whole catalogue (discovery window)")
    add("")
    spa, cash, pbo = mt["spa_alpha"], mt["spa_vs_cash"], mt["pbo"]
    add("| test | result |")
    add("| --- | --- |")
    add(f"| Hansen SPA, null: no candidate has positive alpha | p {_num(spa['p_consistent'], 4)} "
        f"(best `{spa['best']}`) |")
    add(f"| White reality check, same null | p {_num(spa['p_reality_check'], 4)} |")
    add(f"| Hansen SPA, null: no candidate beats bills | p {_num(cash['p_consistent'], 4)} "
        f"(best `{cash['best']}`) |")
    add(f"| Probability of backtest overfitting (CSCV, {pbo['blocks']} blocks, "
        f"{pbo['combinations']} splits) | {_num(pbo['pbo'], 3)} |")
    add(f"| Effective number of trials (mean-correlation adjusted) | "
        f"{_num(mt['effective_trials'], 0)} of {mt['trials']} |")
    add(f"| Candidates significant after Holm / Benjamini-Yekutieli (5%) | "
        f"{len(mt['significant_holm'])} / {len(mt['significant_by'])} |")
    add(f"| Rank correlation of alpha IR, discovery against holdout | "
        f"{_num(mt['discovery_to_holdout_rank_correlation'], 3)} |")
    add("")
    add("SPA and the reality check bootstrap the whole catalogue jointly (stationary bootstrap, "
        f"mean block {proto['bootstrap_mean_block']:.0f} sessions, {proto['bootstrap_draws']} "
        "draws), so they answer whether the best result could be luck given everything tried.")
    add("")
    add("## The ten best discovery candidates, confirmed once on the holdout")
    add("")
    add("| rank | candidate | discovery alpha IR | holdout alpha IR | holdout alpha a year (t) "
        "| holdout Sharpe | break-even cost | alpha at 2x cost | tests passed | verdict |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for c in scan["confirmations"]:
        r = rows[c["id"]]
        d, h = r["discovery"], r["holdout"]
        stressed = (r.get("holdout_2x_cost") or {}).get("alpha")
        add(f"| {c['discovery_rank']} | `{c['id']}` | {_num(d.get('alpha_ir'))} | "
            f"{_num(h.get('alpha_ir'))} | {_pct(h.get('alpha'))} ({_num(h.get('alpha_t'))}) | "
            f"{_num(h.get('sharpe'))} | {_num(h.get('breakeven_cost_multiple'), 1)}x | "
            f"{_pct(stressed)} | {sum(c['tests'].values())} of 5 | {c['verdict']} |")
    add("")
    add("## Families")
    add("")
    add("The share of a family's members with positive holdout alpha is a check that does not "
        "depend on picking one fund.")
    add("")
    add("| family | members | best in discovery | its holdout alpha IR | median holdout alpha IR "
        "| members positive in holdout |")
    add("| --- | --- | --- | --- | --- | --- |")
    for name, f in sorted(scan["families"].items(),
                          key=lambda kv: -(kv[1].get("median_holdout_alpha_ir") or -9)):
        add(f"| {name} | {f['members']} | `{f['best']}` | {_num(f['best_holdout_alpha_ir'])} | "
            f"{_num(f['median_holdout_alpha_ir'])} | "
            f"{_pct(f['share_positive_holdout_alpha'], 0)} |")
    add("")
    add("| family | mechanism | execution | references |")
    add("| --- | --- | --- | --- |")
    for name, f in scan["families"].items():
        add(f"| {name} | {f['mechanism']} | {f['execution']} | {'; '.join(f['references'])} |")
    add("")
    add("## Walk-forward picks")
    add("")
    add("| year | pick (trained on all earlier years) | training alpha IR | that year's excess |")
    add("| --- | --- | --- | --- |")
    for p in wf.get("picks", []):
        add(f"| {p['year']} | `{p['pick']}` | {_num(p['train_alpha_ir'])} | "
            f"{_pct(p['year_excess'])} |")
    add("")
    if spec["candidate"] is not None:
        row = rows[spec["candidate"]["id"]]
        add(f"## Profile of `{row['id']}`")
        add("")
        add(f"Mechanism: {spec['mechanism']} Execution: {spec['execution']}.")
        add("")
        add("| window | years | excess a year | vol | Sharpe | alpha (t) | beta | max drawdown "
            "| compound, idle cash earns nothing |")
        add("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for w in ("discovery", "holdout", "full"):
            m = row[w]
            add(f"| {w} | {m['years']} | {_pct(m['ann_excess'])} | {_pct(m['ann_vol'])} | "
                f"{_num(m['sharpe'])} | {_pct(m['alpha'])} ({_num(m['alpha_t'])}) | "
                f"{_num(m['beta'])} | {_pct(m['max_drawdown'])} | "
                f"{_pct(m['cagr_cash_earns_nothing'])} |")
        add("")
        years = row["full"]["yearly_excess"]
        add("Excess return over bills by calendar year:")
        add("")
        add("| " + " | ".join(years) + " |")
        add("| " + " | ".join("---" for _ in years) + " |")
        add("| " + " | ".join(_pct(v, 1) for v in years.values()) + " |")
        add("")
        add("Caveats found automatically:")
        add("")
        for c in spec["caveats"] or ["none flagged"]:
            add(f"- {c}")
        add("")
    legs = scan.get("leg_decomposition") or {}
    if legs:
        add("## Where each fund earns its return: overnight against intraday (holdout)")
        add("")
        add("Mean bps per session. The last three columns subtract SPY on the same sessions. A "
            "fund whose overnight lead over SPY is handed back intraday, with no close-to-close "
            "difference, owes that lead to where its open and close are printed.")
        add("")
        add("| fund | overnight | intraday | close to close | overnight minus SPY (t) | "
            "intraday minus SPY | close to close minus SPY |")
        add("| --- | --- | --- | --- | --- | --- | --- |")
        for sym in ("SPY", "VTI", "QQQ", "IWM", "VB", "VO", "DIA", "EFA", "TLT", "HYG"):
            h = (legs.get(sym) or {}).get("holdout")
            if h:
                add(f"| {sym} | {_num(h['on_bps'])} | {_num(h['id_bps'])} | {_num(h['cc_bps'])} | "
                    f"{_num(h['on_minus_ref_bps'])} ({_num(h['on_minus_ref_t'], 1)}) | "
                    f"{_num(h['id_minus_ref_bps'])} | {_num(h['cc_minus_ref_bps'])} |")
        add("")
    add("## Buy and hold, for scale")
    add("")
    add("| fund | holdout excess a year | holdout Sharpe | holdout max drawdown | "
        "full-sample Sharpe |")
    add("| --- | --- | --- | --- | --- |")
    for key in ("SPY", "QQQ", "IWM", "VTI", "VB", "TLT", "GLD"):
        b = scan["benchmarks"].get(f"buy_and_hold:{key}")
        if b:
            add(f"| {key} | {_pct(b['holdout']['ann_excess'])} | {_num(b['holdout']['sharpe'])} | "
                f"{_pct(b['holdout']['max_drawdown'])} | {_num(b['full']['sharpe'])} |")
    add("")
    hourly = scan.get("hourly")
    if hourly:
        add("## Hourly last-half-hour families (research only)")
        add("")
        cands = sorted(hourly["candidates"], key=lambda r: -(r["discovery"].get("t") or -9))
        add(f"{len(cands)} candidates on {hourly['sessions']} full sessions, {hourly['first']} to "
            f"{hourly['last']}, holdout from {hourly['holdout_from']}.")
        add("")
        add("| candidate | discovery bps a day (t) | BY p | holdout bps a day (t) |")
        add("| --- | --- | --- | --- |")
        for r in cands[:5]:
            d, h = r["discovery"], r["holdout"]
            add(f"| `{r['id']}` | {_num(d.get('mean_bps_per_day'))} ({_num(d.get('t'))}) | "
                f"{_num(d.get('p_by'), 3)} | {_num(h.get('mean_bps_per_day'))} "
                f"({_num(h.get('t'))}) |")
        add("")
    quality = scan.get("data_quality") or {}
    if quality:
        add("## Data checks")
        add("")
        add("Close-to-close returns rebuilt from raw prices and dividends, compared with the "
            "provider's adjusted close; and the share of sessions whose open equals the previous "
            "close (a sign of a stale open print).")
        add("")
        add("| fund | first bar | sessions | median / max deviation (bps) | stale opens | "
            "legs beyond 15% |")
        add("| --- | --- | --- | --- | --- | --- |")
        for sym, q in quality.items():
            dev = q.get("adjclose_deviation") or {}
            add(f"| {sym} | {q.get('first_date')} | {q.get('bars')} | "
                f"{_num(dev.get('median_bps'), 3)} / {_num(dev.get('max_bps'), 1)} | "
                f"{_pct(q.get('stale_open_share'), 1)} | {q.get('legs_beyond_15pct')} |")
        add("")
    add("## Standing caveats")
    add("")
    for text in STANDING_CAVEATS:
        add(f"- {text}")
    add("")
    add("## Reproduce")
    add("")
    add("```sh\npython -m edgefinder.discover --out edgefinder/results   # add --refresh to refetch\n```")
    add("")
    return "\n".join(lines)


STANDING_CAVEATS = (
    "The bars are public consolidated prices from an unofficial endpoint, and their open is the "
    "first valid trade of the session. A market-on-open order fills at the primary exchange's "
    "opening auction, which can differ from that trade, and Alpaca's paper trading simulates "
    "opening orders at the opening quote, so a paper trial cannot test this. "
    "`python -m edgefinder.auctions` re-prices the selected strategy at the official auction "
    "prints (2016 onwards) and is the test that settles it.",
    "One cost schedule (September 2026 spreads at 2026 prices) is applied to every year. "
    "Spreads were wider in the 2000s, so early-year results are flattered for the "
    "high-turnover families.",
    "The 24-fund universe was chosen in 2026; all its funds survived. Broad index funds rarely "
    "close, but the universe is not a point-in-time list.",
    "Every family and grid was written before the first run, and no protocol constant was "
    "changed after it. The catalogue is still the author's choice of hypotheses; a different "
    "catalogue gives different multiple-testing hurdles.",
    "Taxes are ignored. Strategies that trade every session realise only short-term gains.",
    "Overnight holding carries gap risk that no stop can cap: the position is exposed to "
    "everything that happens while the exchange is shut.",
    "Bills are assumed to be earned on idle cash. The column 'idle cash earns nothing' shows "
    "the result if the broker pays no interest.",
)


def write(scan: Mapping[str, Any], out: Path) -> dict[str, Any]:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.md").write_text(render(scan), encoding="utf-8")
    spec = strategy_spec(scan)
    (out / "strategy.json").write_text(json.dumps(spec, indent=1) + "\n", encoding="utf-8")
    return spec
